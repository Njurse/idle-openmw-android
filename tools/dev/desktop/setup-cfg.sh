#!/usr/bin/env bash
# Generate the OpenMW user config for the idle-openmw dev environment.
#
# Windows OpenMW keeps its user config in
#     %USERPROFILE%\Documents\My Games\OpenMW\
# and reads two files we care about:
#   openmw.cfg    -- data dirs + content (our mod's data path and .omwscripts)
#   settings.cfg  -- engine settings (we pin a window, not exclusive fullscreen,
#                    so a screenshot is possible and the resolution is known)
#
# We point `data=` at the LIVE repo copy (mods/idle_openmw), not a staged copy, so
# editing the mod takes effect on the next launch -- that is the whole point of
# having a real engine to test against.
#
# Idempotent: backs up anything it replaces. Re-run after moving the repo.
#
# Usage: bash tools/dev/desktop/setup-cfg.sh

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
# Windows-style forward-slash path for openmw.cfg (no backslashes: they are
# escape characters in OpenMW's quoted strings, and in bash they are worse).
REPO_WIN="$(cd "$REPO" && pwd -W 2>/dev/null || echo "$REPO")"

CONFIG_DIR="${OMW_CONFIG_DIR:-$USERPROFILE/Documents/My Games/OpenMW}"
MOD_DATA="$REPO_WIN/mods/idle_openmw"
MW_DATA="$REPO_WIN/gamedata/Data Files"

mkdir -p "$CONFIG_DIR"
STAMP="$(date +%Y%m%d-%H%M%S)"

for f in openmw.cfg settings.cfg; do
  if [[ -f "$CONFIG_DIR/$f" ]]; then
    cp "$CONFIG_DIR/$f" "$CONFIG_DIR/$f.bak-$STAMP"
    echo "backed up $f -> $f.bak-$STAMP"
  fi
done

# --- openmw.cfg -------------------------------------------------------------
# Mod first so its loose files (mygui overrides) take precedence over the
# Morrowind data, then the game data. Content: the three ESMs, then our script
# manifest last.
cat > "$CONFIG_DIR/openmw.cfg" <<EOF
# Generated by tools/dev/desktop/setup-cfg.sh -- do not edit by hand.
# The idle-openmw dev environment: the live repo mod + the staged Morrowind data.
data="$MOD_DATA"
data="$MW_DATA"
content=Morrowind.esm
content=Tribunal.esm
content=Bloodmoon.esm
content=idle_openmw.omwscripts
EOF

# --- settings.cfg -----------------------------------------------------------
# A windowed, fixed-resolution, vsync-off window: screenshots are possible, the
# size is known, and nothing asks the GPU for exotic features on a dev box.
cat > "$CONFIG_DIR/settings.cfg" <<EOF
# Generated by tools/dev/desktop/setup-cfg.sh -- do not edit by hand.
[Video]
resolution x = 1600
resolution y = 900
fullscreen = false
window border = true
vsync = false
antialiasing = 0
framerate limit = 60

[GUI]
scaling factor = 1.0

[Camera]
view over shoulder = false
field of view = 55
EOF

echo
echo "wrote:"
echo "  $CONFIG_DIR/openmw.cfg"
echo "  $CONFIG_DIR/settings.cfg"
echo
echo "data dirs:"
grep -E '^data=' "$CONFIG_DIR/openmw.cfg" | sed 's/^/  /'
echo "content:"
grep -E '^content=' "$CONFIG_DIR/openmw.cfg" | sed 's/^/  /'
echo
for p in "$MOD_DATA" "$MW_DATA"; do
  if [[ -e "$p" ]]; then echo "  ok      $p"; else echo "  MISSING $p"; fi
done
