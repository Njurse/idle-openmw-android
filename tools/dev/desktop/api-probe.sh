#!/usr/bin/env bash
# Ask an OpenMW install what its Lua API actually exposes.
#
# Runs the menu-context probe mod (tools/dev/desktop/api-probe) against an engine
# and prints the single API_PROBE line the engine logs.
#
# HOW IT ISOLATES ITSELF
# ----------------------
# OpenMW reads openmw.cfg from the *default* config dir and writes its log there;
# `--user-data` moves only saves/screenshots, and `--replace content` on the command
# line replaces the file's content with the (empty) command line. So the reliable
# way to run a different config is to swap the default one aside for the duration
# and put it back afterwards. That is what this does, with a backup either way.
#
# Usage:
#   bash tools/dev/desktop/api-probe.sh "F:/Games/OpenMW-0.51"
#   bash tools/dev/desktop/api-probe.sh "F:/Games/OpenMW Latest"
#
# This is how the supported-engine floor in docs/openmw-lua-api.md is measured.

set -euo pipefail

ENGINE="${1:-F:/Games/OpenMW-0.51}"
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && (pwd -W 2>/dev/null || pwd) | sed 's#\\#/#g')"
PROBE="$REPO/tools/dev/desktop/api-probe"
MW_DATA="$REPO/gamedata/Data Files"
CONFIG_DIR="${OMW_CONFIG_DIR:-$USERPROFILE/Documents/My Games/OpenMW}"
LOG="$CONFIG_DIR/openmw.log"

[[ -f "$ENGINE/openmw.exe" ]] || { echo "!! no openmw.exe in $ENGINE" >&2; exit 1; }
[[ -f "$PROBE/api_probe.omwscripts" ]] || { echo "!! probe mod missing" >&2; exit 1; }

mkdir -p "$CONFIG_DIR"
STAMP="$$"
restore() {
  for f in openmw.cfg settings.cfg; do
    if [[ -f "$CONFIG_DIR/$f.probe-bak" ]]; then
      mv -f "$CONFIG_DIR/$f.probe-bak" "$CONFIG_DIR/$f"
    else
      rm -f "$CONFIG_DIR/$f"
    fi
  done
}
trap restore EXIT

for f in openmw.cfg settings.cfg; do
  [[ -f "$CONFIG_DIR/$f" ]] && cp "$CONFIG_DIR/$f" "$CONFIG_DIR/$f.probe-bak" || true
done

cat > "$CONFIG_DIR/openmw.cfg" <<EOF
# generated by api-probe.sh (temporary) -- the caller's config is restored on exit
data="$PROBE"
data="$MW_DATA"
fallback-archive=Morrowind.bsa
fallback-archive=Tribunal.bsa
fallback-archive=Bloodmoon.bsa
content=Morrowind.esm
content=api_probe.omwscripts
EOF
cat > "$CONFIG_DIR/settings.cfg" <<EOF
[Video]
resolution x = 640
resolution y = 480
fullscreen = false
vsync = false
EOF

echo "probing $(head -1 "$ENGINE/resources/version" 2>/dev/null) at $ENGINE"
taskkill //IM openmw.exe //F >/dev/null 2>&1 || true
rm -f "$LOG"
sleep 1

powershell.exe -NoProfile -Command \
  "Start-Process -FilePath '$(cygpath -w "$ENGINE/openmw.exe" 2>/dev/null || echo "$ENGINE/openmw.exe")' -ArgumentList '--no-sound'" \
  >/dev/null 2>&1 </dev/null

for _ in $(seq 1 45); do
  [[ -f "$LOG" ]] && grep -q "API_PROBE" "$LOG" 2>/dev/null && break
  sleep 1
done
taskkill //IM openmw.exe //F >/dev/null 2>&1 || true

echo
if grep -q "API_PROBE" "$LOG" 2>/dev/null; then
  grep -h "API_PROBE" "$LOG" | tail -1
else
  echo "(no API_PROBE line -- the probe did not run). Engine log tail:"
  tail -n 12 "$LOG" 2>/dev/null || echo "(no log)"
  exit 1
fi
