-- tests/spec/notify_spec.lua
-- The notification queue behind "tell me when they reach a town".
describe('idle.notify', function()
  local notify = require('scripts.idle.notify')

  it('holds entries until the runtime drains them', function()
    local q = notify.new()
    q:push('arrival', 'Arrived in Balmora', nil, 'notable', 10)
    assert.equals(q:pendingCount(), 1)

    local drained = q:drain()
    assert.equals(#drained, 1)
    assert.equals(drained[1].title, 'Arrived in Balmora')
    assert.equals(drained[1].kind, 'arrival')
    assert.equals(drained[1].time, 10)
    -- draining twice must not re-deliver
    assert.equals(#q:drain(), 0)
  end)

  it('maps named priorities to numbers', function()
    local q = notify.new()
    -- push(kind, title, detail, priority, time): nil detail, then priority
    assert.equals(q:push('a', 'info', nil, 'info').priority, 1)
    assert.equals(q:push('a', 'notable', nil, 'notable').priority, 2)
    assert.equals(q:push('a', 'urgent', nil, 'urgent').priority, 3)
    assert.equals(q:push('a', 'nonsense', nil, 'nonsense').priority, 1)
    assert.equals(q:push('a', 'x', nil, 9).priority, 3)
    assert.equals(q:push('a', 'x', nil, 0).priority, 1)
  end)

  it('defaults to info when the priority is omitted entirely', function()
    local q = notify.new()
    assert.equals(q:push('arrival', 'Reached Balmora').priority, 1)
  end)

  it('peeks without consuming', function()
    local q = notify.new()
    q:push('arrival', 'One')
    assert.equals(#q:peek(), 1)
    assert.equals(#q:peek(), 1)
    assert.equals(q:pendingCount(), 1)
  end)

  it('bounds its history and counts what fell off', function()
    local q = notify.new({ limit = 3 })
    for i = 1, 5 do q:push('milestone', 'event ' .. i) end
    assert.equals(q.limit, 3)
    local recent = q:recent(10)
    assert.equals(#recent, 3)
    assert.equals(recent[1].title, 'event 5')   -- newest first
    assert.equals(recent[3].title, 'event 3')
    assert.equals(q.dropped, 2)
  end)

  it('reports the most important pending entry', function()
    local q = notify.new()
    q:push('arrival', 'quiet', nil, 'info')
    q:push('danger', 'hurt badly', nil, 'urgent')
    q:push('milestone', 'ding', nil, 'notable')
    assert.equals(q:mostImportant().title, 'hurt badly')
    assert.is_nil(notify.new():mostImportant())
  end)

  it('can drop low-priority noise', function()
    local q = notify.new()
    q:push('a', 'info', nil, 'info')
    q:push('b', 'notable', nil, 'notable')
    q:push('c', 'urgent', nil, 'urgent')
    local kept = q:dropBelow('notable')
    assert.equals(kept, 1)
    assert.equals(q:pendingCount(), 1)
    assert.equals(q:peek()[1].title, 'urgent')
  end)

  it('clears everything on request', function()
    local q = notify.new()
    q:push('a', 'x')
    q:clear()
    assert.equals(q:pendingCount(), 0)
    assert.equals(#q:recent(10), 0)
  end)

  it('handles an empty queue', function()
    local q = notify.new()
    assert.equals(#q:drain(), 0)
    assert.is_nil(q:mostImportant())
    assert.equals(#q:recent(5), 0)
  end)

  it('defaults a missing kind and title rather than erroring', function()
    local q = notify.new()
    local entry = q:push()
    assert.equals(entry.kind, 'info')
    assert.equals(entry.title, '')
    assert.equals(entry.priority, 1)
  end)
end)
