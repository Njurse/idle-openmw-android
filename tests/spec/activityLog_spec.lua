describe('idle.activityLog', function()
  local activityLog = require('scripts.idle.activityLog')

  it('appends and reads back entries', function()
    local log = activityLog.new(10)
    log:add('Walking to Arrille\'s Tradehouse', 'info', 10)
    log:add('Sold 5 chitin weapons for 120 gold', 'good', 20)
    assert.equals(log:count(), 2)
    assert.equals(log:lastMessage(), 'Sold 5 chitin weapons for 120 gold')
    local recent = log:recent(2)
    assert.equals(recent[1].message, 'Walking to Arrille\'s Tradehouse')
    assert.equals(recent[2].level, 'good')
  end)

  it('drops the oldest entries past the limit', function()
    local log = activityLog.new(3)
    for i = 1, 5 do log:add('line ' .. i, 'info', i) end
    assert.equals(log:count(), 3)
    local all = log:all()
    assert.equals(all[1].message, 'line 3')
    assert.equals(all[3].message, 'line 5')
  end)

  it('throttles repeated messages with addOnce', function()
    local log = activityLog.new(10)
    assert.is_not_nil(log:addOnce('stuck', 'Stuck!', 'warn', 100, 30))
    assert.is_nil(log:addOnce('stuck', 'Stuck!', 'warn', 110, 30))
    assert.is_not_nil(log:addOnce('stuck', 'Stuck!', 'warn', 140, 30))
    assert.equals(log:count(), 2)
  end)

  it('finds entries by substring', function()
    local log = activityLog.new(10)
    log:add('Sold a chitin dagger', 'good', 1)
    log:add('Sold a chitin spear', 'good', 2)
    log:add('Rested 8 hours', 'info', 3)
    assert.equals(#log:find('Sold'), 2)
    assert.equals(#log:find('Rested'), 1)
  end)

  it('clears', function()
    local log = activityLog.new(10)
    log:add('x', 'info', 1)
    log:clear()
    assert.equals(log:count(), 0)
    assert.is_nil(log:last())
  end)

  it('formats simulated time', function()
    assert.equals(activityLog.formatTime(0), '0m')
    assert.equals(activityLog.formatTime(59), '0m')
    assert.equals(activityLog.formatTime(60 * 12), '12m')
    assert.equals(activityLog.formatTime(3600 * 5 + 60 * 3), '5h 03m')
  end)

  it('renders lines with timestamps', function()
    local log = activityLog.new(10)
    log:add('Rested 8 hours', 'info', 3600 * 5 + 60 * 3)
    local lines = log:toLines(1)
    assert.equals(lines[1], '5h 03m  Rested 8 hours')
  end)
end)
