describe('idle.directive', function()
  local directive = require('scripts.idle.directive')

  it('maps known directive ids to goals', function()
    assert.equals(directive.GOAL_FOR.shop, 'shop')
    assert.equals(directive.GOAL_FOR.sell, 'sell_junk')
    assert.equals(directive.GOAL_FOR.sell_junk, 'sell_junk')
    assert.is_true(directive.isKnown('rest'))
    assert.is_false(directive.isKnown('conquer-the-world'))
    assert.is_true(#directive.ids() >= 6)
  end)

  it('rejects unknown directives', function()
    local queue = directive.new()
    assert.is_nil(queue:push('nonsense', nil, 0))
    assert.equals(queue:size(), 0)
  end)

  it('queues, peeks and pops in order', function()
    local queue = directive.new(100)
    queue:push('shop', nil, 0)
    queue:push('rest', nil, 0)
    assert.equals(queue:size(), 2)
    assert.equals(queue:peek(0).id, 'shop')
    assert.equals(queue:pop().id, 'shop')
    assert.equals(queue:peek(0).id, 'rest')
  end)

  it('expires directives once the TTL lapses', function()
    local queue = directive.new(60)
    queue:push('shop', nil, 0)
    assert.is_not_nil(queue:peek(59))
    assert.is_nil(queue:peek(60))
    assert.equals(queue:size(), 0)
  end)

  it('clears everything on demand', function()
    local queue = directive.new()
    queue:push('shop', nil, 0)
    queue:push('rest', nil, 0)
    queue:clear()
    assert.equals(queue:size(), 0)
    assert.is_nil(queue:peek(0))
  end)

  it('describes the active directive with time remaining', function()
    local queue = directive.new(120)
    queue:push('train', nil, 0)
    assert.is_true(queue:describe(30):find('train', 1, true) ~= nil)
    assert.is_true(queue:describe(30):find('90s', 1, true) ~= nil)
    assert.is_nil(queue:describe(999))
  end)
end)
